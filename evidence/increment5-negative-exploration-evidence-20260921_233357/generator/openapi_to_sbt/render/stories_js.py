"""Render stories.<slug>.js: reusable per-entity creation bthreads wired
through typed 'Done:' completion events (so generated identifiers flow into
dependent operations), a state-tracking monitor, and reverse-order deletion
lifecycle bthreads. Contains no fault-injection / seeded-bug content: only
contract-derived CRUD and dependency wiring (DEVELOPMENT_PROMPT.md #10).
"""
from __future__ import annotations

from typing import Dict, List, Optional, Tuple

from .plan import EntityPlan, Plan
from .naming import js_string, safe_identifier, to_camel
from ..inference.values import generate_value

HEADER = '''// Auto-generated stories for {slug}
// Generated by openapi_to_sbt. Do not edit by hand; regenerate instead.
//@provengo summon rest

function resolveDependencies(deps, pkMap) {{
  let captured = {{}};
  while (Object.keys(deps).length > 0) {{
    let missingEventSets = Object.values(deps);
    let e = sync({{waitFor: missingEventSets}});
    for (let k in deps) {{
      if (deps[k].contains(e)) {{
        let val = (e.data && e.data[k]);
        if (!val && pkMap && pkMap[k]) {{
            let mappedKey = pkMap[k];
            val = (e.data && e.data[mappedKey]);
        }}
        if (!val && e.data) {{
          for (let f in e.data) {{ if (f.toLowerCase().indexOf("id") > -1) {{ val = e.data[f]; break; }} }}
        }}
        if (val !== undefined) {{
            captured[k] = val;
            delete deps[k];
        }}
      }}
    }}
  }}
  return captured;
}}
'''

def _action_story_label(op_plan) -> str:
    if op_plan.kind == "update":
        return f"update:{op_plan.js_name}:1"
    if op_plan.own_entity_key:
        return f"action:{op_plan.js_name}:1"
    return f"standalone:{op_plan.js_name}:1"


def _state_field(ep: EntityPlan) -> str:
    return to_camel(ep.entity.plural_display_name)


def render_state_tracker(entity_plans: List[EntityPlan]) -> str:
    creators = [ep for ep in entity_plans if ep.create_op]
    fields = ", ".join(f"{_state_field(ep)}: []" for ep in creators)
    wait_sets = ", ".join(f"matchAny{ep.entity.plural_display_name}Added()" for ep in creators)
    lines = [
        "// ==============================================================================",
        "// STATE TRACKER (contract-derived: tracks identifiers returned by create operations)",
        "// ==============================================================================",
        f"const STATE = {{ {fields} }};",
        "",
        'bthread("monitor:StateTracker", function() {',
        "    while (true) {",
        f"        let e = sync({{ waitFor: [{wait_sets}] }});",
    ]
    for i, ep in enumerate(creators):
        key0 = ep.key.fields[0] if len(ep.key.fields) == 1 else None
        cond = "if" if i == 0 else "else if"
        # Dispatch on the unique __entityKey tag embedded in the event
        # data, not on description-text prefix matching alone: two
        # different entities can share the exact same OpenAPI summary
        # (confirmed on NetBox -- 'Interface' and 'VMInterface' both
        # document their create op as "Post a list of interface
        # objects."), which made this if/else-if chain permanently
        # misattribute the second entity's events to the first,
        # leaving its own STATE array empty forever.
        lines.append(f'        {cond} (e.data && e.data["__entityKey"] === {js_string(ep.entity.key)}) {{')
        if key0:
            js_key0 = safe_identifier(key0)
            lines.append(f"            STATE.{_state_field(ep)}.push(e.data.{js_key0});")
        else:
            lines.append(f"            STATE.{_state_field(ep)}.push(e.data);")
        lines.append("        }")
    lines.append("    }")
    lines.append("});")
    return "\n".join(lines)


def _value_js(value) -> str:
    import json as _json
    return _json.dumps(value)


def _dependency_assignment_expr(js_field: str, target_ep: EntityPlan, field_schema: Dict) -> str:
    """Render a captured dependency value in the request shape required by OpenAPI.

    Scalar FK fields (e.g. ``authorId``) consume the captured key directly.
    Nested reference objects (e.g. ``site: {id: ...}``) wrap that same runtime
    key in the documented object shape.  Schema-aware dependency inference only
    accepts single-key nested references, so this renderer intentionally mirrors
    that conservative boundary.
    """
    captured = f'captured[{js_string(js_field)}]'
    if isinstance(field_schema, dict) and field_schema.get("type") == "object":
        props = field_schema.get("properties", {})
        if isinstance(props, dict) and len(target_ep.key.fields) == 1:
            raw_key = target_ep.key.fields[0]
            if raw_key in props:
                return "{" + js_string(raw_key) + ": " + captured + "}"
    return captured


def _dependency_instance_index(instance: int, dependency_position: int, count: int) -> int:
    """Deterministic generic fan-out/cross-binding schedule."""
    if instance == 1:
        return 1
    # Instances 2--3 vary the first dependency while every other dependency
    # remains shared. Instances 4--5 keep dependency 0 shared and vary every
    # remaining dependency together. With only five ordinary CRUD instances,
    # this guarantees three-way fan-out on dependency 0 and cross-binding on
    # every additional dependency, including entities with 3+ foreign keys.
    value = 2 + ((instance - 2) % 2)
    if instance <= 3:
        return min(value, count) if dependency_position == 0 else 1
    return 1 if dependency_position == 0 else min(value, count)


def _required_js_fields(op_plan) -> set:
    required = {safe_identifier(p.name) for p in op_plan.op.parameters if p.required}
    if op_plan.op.request_body:
        for variant in op_plan.op.request_body.variants[:1]:
            schema_required = variant.schema.get("required", []) if isinstance(variant.schema, dict) else []
            required.update(safe_identifier(name) for name in schema_required)
            properties = variant.schema.get("properties", {}) if isinstance(variant.schema, dict) else {}
            for name, schema in properties.items():
                if isinstance(schema, dict) and schema.get("minLength", 0) >= 1:
                    required.add(safe_identifier(name))
    return required


def _op_args(op_plan, values: Dict[str, str]) -> str:
    return ", ".join(values.get(param, "undefined") for param in op_plan.params)


def _single_key_var(entity_plan: EntityPlan, role: str) -> Tuple[str, str]:
    raw_key = entity_plan.key.fields[0]
    return safe_identifier(raw_key), f"__{role}Id"


def _minimal_values(op_plan, prefix: str, seed: int,
                    dependency_values: Optional[Dict[str, str]] = None,
                    carry_values: Optional[Dict[str, str]] = None) -> Tuple[List[str], Dict[str, str]]:
    """Produce contract-derived values only for required/minLength fields.

    The returned mapping is suitable for a full generated interface signature;
    every omitted optional argument becomes JavaScript ``undefined`` and is
    therefore excluded by the interface serializer.
    """
    dependency_values = dependency_values or {}
    carry_values = carry_values or {}
    required = _required_js_fields(op_plan)
    declarations: List[str] = []
    values: Dict[str, str] = dict(dependency_values)
    for param in op_plan.params:
        if param in values:
            continue
        if param in carry_values:
            values[param] = carry_values[param]
            continue
        if param not in required:
            continue
        schema = _schema_for_op_field(op_plan, param)
        value = generate_value(schema, seed, f"validated-lifecycle.{prefix}.{param}", for_request=True)
        variable = f"__{prefix}_{param}"
        declarations.append(f"  let {variable} = {_value_js(value)};")
        values[param] = variable
    return declarations, values


def _select_update_operation(entity_plan: EntityPlan):
    """Choose a deterministic update and a safe scalar field from OpenAPI.

    PUT is preferred because its ordinary object schema is generally more
    portable than JSON Patch arrays.  Candidate fields exclude identifiers and
    relationship-shaped names; booleans are preferred, then enums, then simple
    strings/numbers.
    """
    operations = [op for op in entity_plan.ops if op.kind == "update" and op.op.request_body]
    operations.sort(key=lambda op: (0 if op.op.method == "PUT" else 1, op.op.path, op.js_name))
    key_names = {_norm_key(name) for name in entity_plan.key.fields}
    ranked = []
    for operation in operations:
        schemas = _request_body_schemas_for_operation(operation)
        for raw_name, schema in schemas.items():
            normalized = _norm_key(raw_name)
            if (normalized in key_names or normalized.endswith("id") or
                    schema.get("readOnly") or schema.get("type") in ("object", "array")):
                continue
            if schema.get("type") == "boolean":
                rank = 0
            elif schema.get("enum"):
                rank = 1
            elif schema.get("type") == "string" and not schema.get("format"):
                rank = 2
            elif schema.get("type") in ("integer", "number"):
                rank = 3
            else:
                continue
            method_rank = 0 if operation.op.method == "PUT" else 1
            ranked.append((rank, method_rank, safe_identifier(raw_name), raw_name, schema, operation))
    if not ranked:
        return None
    ranked.sort(key=lambda item: (item[0], item[1], item[2], item[5].js_name))
    return ranked[0]


def _select_stable_resource_update(entity_plan: EntityPlan):
    """Prefer a descriptive scalar update for resource verifier profiles.

    Lifecycle-control booleans such as ``is_archived`` are valid OpenAPI
    values but can disable later operations and therefore confound a verifier
    campaign.  A title/name/description field is a safer persistence witness.
    """
    operations = [op for op in entity_plan.ops if op.kind == "update" and op.op.request_body]
    operations.sort(key=lambda op: (0 if op.op.method == "PUT" else 1, op.op.path, op.js_name))
    preferred = ("title", "name", "description")
    candidates = []
    for operation in operations:
        for raw_name, schema in _request_body_schemas_for_operation(operation).items():
            normalized = _norm_key(raw_name)
            if normalized not in preferred or schema.get("readOnly"):
                continue
            if schema.get("type") != "string" or schema.get("format"):
                continue
            candidates.append((preferred.index(normalized),
                               0 if operation.op.method == "PUT" else 1,
                               safe_identifier(raw_name), raw_name, schema, operation))
    if candidates:
        candidates.sort(key=lambda item: (item[0], item[1], item[2], item[5].js_name))
        return candidates[0]
    return _select_update_operation(entity_plan)


def _norm_key(value: str) -> str:
    return "".join(ch for ch in value.lower() if ch.isalnum())


def _request_body_schemas_for_operation(op_plan) -> Dict[str, Dict]:
    if not op_plan.op.request_body:
        return {}
    for variant in op_plan.op.request_body.variants:
        schema = variant.schema if isinstance(variant.schema, dict) else {}
        props = schema.get("properties", {})
        if isinstance(props, dict) and props:
            return {name: value for name, value in props.items() if isinstance(value, dict)}
    return {}


def _association_operations(child: EntityPlan, auxiliary_key: str):
    posts = [op for op in child.ops
             if op.kind == "action" and op.op.method == "POST"
             and child.entity.key in {target for _, target in op.story_dependencies}
             and auxiliary_key in {target for _, target in op.story_dependencies}]
    for attach in sorted(posts, key=lambda op: (op.op.path, op.js_name)):
        listing = next((op for op in child.ops
                        if op.kind == "action" and op.op.method == "GET"
                        and op.op.path == attach.op.path), None)
        detach = next((op for op in child.ops
                       if op.kind == "action" and op.op.method == "DELETE"
                       and op.op.path.startswith(attach.op.path + "/")
                       and auxiliary_key in {target for _, target in op.story_dependencies}), None)
        if listing and detach:
            return attach, listing, detach
    return None


def _select_validated_lifecycle(plan: Plan):
    by_key = {ep.entity.key: ep for ep in plan.entities}
    complete = [ep for ep in plan.entities
                if ep.create_op and ep.get_op and ep.delete_op and len(ep.key.fields) == 1]
    for child in sorted(complete, key=lambda ep: ep.entity.key):
        update = _select_update_operation(child)
        if not update:
            continue
        for dependency in child.dependencies:
            parent = by_key.get(dependency.target)
            if parent not in complete:
                continue
            for auxiliary in sorted(complete, key=lambda ep: ep.entity.key):
                if auxiliary.entity.key in (child.entity.key, parent.entity.key):
                    continue
                association = _association_operations(child, auxiliary.entity.key)
                if association:
                    return parent, child, auxiliary, dependency, update, association
    return None


def render_validated_lifecycle(plan: Plan) -> str:
    selected = _select_validated_lifecycle(plan)
    if not selected:
        return ('// validated-lifecycle: no unambiguous parent/child/association '
                'chain could be derived from this OpenAPI contract.\n')
    parent, child, auxiliary, dependency, update_selection, association = selected
    _rank, _method_rank, update_js_field, update_raw_field, update_schema, update_op = update_selection
    attach_op, list_op, detach_op = association

    parent_key, parent_id = _single_key_var(parent, "parent")
    child_key, child_id = _single_key_var(child, "child")
    auxiliary_key, auxiliary_id = _single_key_var(auxiliary, "auxiliary")
    lines = ['bthread("validated-lifecycle:contract-derived", function() {']

    parent_decls, parent_values = _minimal_values(parent.create_op, "parentCreate", plan.seed)
    lines.extend(parent_decls)
    lines.append(f"  let __parentCreate = {parent.create_op.js_name}({_op_args(parent.create_op, parent_values)});")
    lines.append(f'  let {parent_id} = __parentCreate.data[{js_string(parent_key)}];')
    lines.append(f"  {parent.get_op.js_name}({_op_args(parent.get_op, {parent_key: parent_id})});")

    child_dependency_values = {safe_identifier(dependency.field_name): parent_id}
    child_decls, child_values = _minimal_values(
        child.create_op, "childCreate", plan.seed, dependency_values=child_dependency_values
    )
    lines.extend(child_decls)
    lines.append(f"  let __childCreate = {child.create_op.js_name}({_op_args(child.create_op, child_values)});")
    lines.append(f'  let {child_id} = __childCreate.data[{js_string(child_key)}];')
    lines.append(f"  {child.get_op.js_name}({_op_args(child.get_op, {child_key: child_id})});")

    carry = {param: expr for param, expr in child_values.items()
             if param in _required_js_fields(update_op)}
    update_decls, update_values = _minimal_values(
        update_op, "childUpdate", plan.seed,
        dependency_values={child_key: child_id}, carry_values=carry
    )
    if update_schema.get("type") == "boolean":
        update_expr = "true"
    elif update_schema.get("enum"):
        update_expr = _value_js(update_schema["enum"][0])
    else:
        update_expr = _value_js(generate_value(
            update_schema, plan.seed + 1,
            f"validated-lifecycle.update.{update_raw_field}", for_request=True
        ))
    update_values[update_js_field] = update_expr
    lines.extend(update_decls)
    lines.append(f"  {update_op.js_name}({_op_args(update_op, update_values)});")
    lines.append(f"  {child.get_op.js_name}({_op_args(child.get_op, {child_key: child_id})});")

    auxiliary_decls, auxiliary_values = _minimal_values(
        auxiliary.create_op, "auxiliaryCreate", plan.seed
    )
    lines.extend(auxiliary_decls)
    lines.append(f"  let __auxiliaryCreate = {auxiliary.create_op.js_name}({_op_args(auxiliary.create_op, auxiliary_values)});")
    lines.append(f'  let {auxiliary_id} = __auxiliaryCreate.data[{js_string(auxiliary_key)}];')
    lines.append(f"  {auxiliary.get_op.js_name}({_op_args(auxiliary.get_op, {auxiliary_key: auxiliary_id})});")

    def association_values(op_plan):
        values = {}
        for field, target in op_plan.story_dependencies:
            if target == child.entity.key:
                values[field] = child_id
            elif target == auxiliary.entity.key:
                values[field] = auxiliary_id
        return values

    lines.append(f"  {attach_op.js_name}({_op_args(attach_op, association_values(attach_op))});")
    lines.append(f"  {list_op.js_name}({_op_args(list_op, association_values(list_op))});")
    lines.append(f"  {detach_op.js_name}({_op_args(detach_op, association_values(detach_op))});")
    lines.append(f"  {list_op.js_name}({_op_args(list_op, association_values(list_op))});")
    lines.append(f"  {child.delete_op.js_name}({_op_args(child.delete_op, {child_key: child_id})});")
    lines.append(f"  {auxiliary.delete_op.js_name}({_op_args(auxiliary.delete_op, {auxiliary_key: auxiliary_id})});")
    lines.append(f"  {parent.delete_op.js_name}({_op_args(parent.delete_op, {parent_key: parent_id})});")
    lines.append('  sync({ request: Event("ValidatedLifecycleComplete") });')
    lines.append("});")
    return "\n".join(lines)


def _select_action_lifecycle(plan: Plan):
    """Find a contract-derived parent/entity/subresource CRUD chain."""
    by_key = {ep.entity.key: ep for ep in plan.entities}
    for child in sorted(plan.entities, key=lambda ep: ep.entity.key):
        if not (child.create_op and child.get_op and child.delete_op and len(child.key.fields) == 1):
            continue
        parent = next((by_key.get(dep.target) for dep in child.dependencies
                       if by_key.get(dep.target) and by_key[dep.target].create_op), None)
        if not parent:
            continue
        actions = [op for op in child.ops if op.kind == "action"]
        for create in sorted((op for op in actions if op.op.method == "POST"), key=lambda op: op.op.path):
            base = create.op.path
            listing = next((op for op in actions if op.op.method == "GET" and op.op.path == base), None)
            item_ops = [op for op in actions if op.op.path.startswith(base + "/{")]
            read = next((op for op in item_ops if op.op.method == "GET"), None)
            update = next((op for op in item_ops if op.op.method == "PUT" and op.op.request_body), None)
            delete = next((op for op in item_ops if op.op.method == "DELETE"), None)
            if not all((listing, read, update, delete)):
                continue
            props = _request_body_schemas_for_operation(update)
            writable = [(raw, schema) for raw, schema in props.items()
                        if not schema.get("readOnly") and schema.get("type") in ("string", "boolean", "integer", "number")]
            if not writable:
                continue
            writable.sort(key=lambda item: (0 if item[1].get("type") == "string" else 1, item[0]))
            return parent, child, create, listing, read, update, delete, writable[0]
    return None


def render_validated_action_lifecycle(plan: Plan) -> str:
    selected = _select_action_lifecycle(plan)
    if not selected:
        return "// validated-action-lifecycle: no complete subresource lifecycle was derived.\n"
    parent, child, create, listing, read, update, delete, (raw_field, field_schema) = selected
    parent_key, parent_id = _single_key_var(parent, "parent")
    child_key, child_id = _single_key_var(child, "child")
    item_param = next(p.name for p in read.op.parameters if p.location == "path"
                      and safe_identifier(p.name) not in {field for field, _ in read.story_dependencies})
    item_js = safe_identifier(item_param)
    item_id = "__subresourceId"
    value_js = safe_identifier(raw_field)
    initial = _value_js(generate_value(field_schema, plan.seed, "validated-action.create", for_request=True))
    changed = _value_js(generate_value(field_schema, plan.seed + 1, "validated-action.update", for_request=True))
    lines = ['bthread("validated-action-lifecycle:contract-derived", function() {']
    decls, values = _minimal_values(parent.create_op, "parentCreate", plan.seed)
    lines += decls
    lines.append(f"  let __parentCreate = {parent.create_op.js_name}({_op_args(parent.create_op, values)});")
    lines.append(f'  let {parent_id} = __parentCreate.data[{js_string(parent_key)}];')
    lines.append(f"  {parent.get_op.js_name}({_op_args(parent.get_op, {parent_key: parent_id})});")
    dep = next(d for d in child.dependencies if d.target == parent.entity.key)
    decls, child_values = _minimal_values(child.create_op, "childCreate", plan.seed,
                                           dependency_values={safe_identifier(dep.field_name): parent_id})
    lines += decls
    lines.append(f"  let __childCreate = {child.create_op.js_name}({_op_args(child.create_op, child_values)});")
    lines.append(f'  let {child_id} = __childCreate.data[{js_string(child_key)}];')
    lines.append(f"  {child.get_op.js_name}({_op_args(child.get_op, {child_key: child_id})});")

    def action_values(op, extra=None):
        result = {field: child_id for field, target in op.story_dependencies if target == child.entity.key}
        if extra: result.update(extra)
        return result

    lines.append(f"  let __initialValue = {initial};")
    created = action_values(create, {value_js: "__initialValue"})
    lines.append(f"  let __subresourceCreate = {create.js_name}({_op_args(create, created)});")
    # Action operations do not have an entity key in their generated signature,
    # so server-assigned IDs remain inside the captured raw HTTP response.
    # Keep a defensive direct-data fallback for contracts that do expose it.
    lines.append(
        f'  let {item_id} = (__subresourceCreate.data["id"] !== undefined '
        f'? __subresourceCreate.data["id"] : __subresourceCreate.data.__httpResponse["id"]);'
    )
    lines.append(f"  {read.js_name}({_op_args(read, action_values(read, {item_js: item_id}))});")
    lines.append(f"  {listing.js_name}({_op_args(listing, action_values(listing))});")
    lines.append(f"  let __updatedValue = {changed};")
    update_values = action_values(update, {item_js: item_id, value_js: "__updatedValue"})
    lines.append(f"  {update.js_name}({_op_args(update, update_values)});")
    lines.append(f"  {read.js_name}({_op_args(read, action_values(read, {item_js: item_id}))});")
    lines.append(f"  {delete.js_name}({_op_args(delete, action_values(delete, {item_js: item_id}))});")
    lines.append(f"  {listing.js_name}({_op_args(listing, action_values(listing))});")
    lines.append(f"  {child.delete_op.js_name}({_op_args(child.delete_op, {child_key: child_id})});")
    lines.append(f"  {parent.delete_op.js_name}({_op_args(parent.delete_op, {parent_key: parent_id})});")
    lines.append('  sync({ request: Event("ValidatedActionLifecycleComplete") });')
    lines.append("});")
    return "\n".join(lines)


def _select_relation_lifecycle(plan: Plan):
    """Find a self-relation action on a creatable child entity.

    The selection is contract-derived: a POST collection ending in
    ``/relations`` plus a DELETE item below it, both owned by the same entity.
    """
    by_key = {ep.entity.key: ep for ep in plan.entities}
    for child in sorted(plan.entities, key=lambda ep: ep.entity.key):
        if not (child.create_op and child.get_op and child.delete_op and len(child.key.fields) == 1):
            continue
        parent = next((by_key.get(dep.target) for dep in child.dependencies
                       if by_key.get(dep.target) and by_key[dep.target].create_op
                       and by_key[dep.target].get_op and by_key[dep.target].delete_op), None)
        if not parent:
            continue
        creates = [op for op in child.ops if op.kind == "action" and op.op.method == "POST"
                   and op.op.path.rstrip("/").endswith("/relations")]
        for create in sorted(creates, key=lambda op: op.op.path):
            delete = next((op for op in child.ops if op.kind == "action"
                           and op.op.method == "DELETE"
                           and op.op.path.startswith(create.op.path + "/")), None)
            if not delete:
                continue
            create_props = _request_body_schemas_for_operation(create)
            other = next((safe_identifier(name) for name in create_props
                          if "other" in _norm_key(name) and _norm_key(name).endswith("id")), None)
            relation = next((safe_identifier(name) for name in create_props
                             if "relation" in _norm_key(name) and create_props[name].get("enum")), None)
            if not (other and relation):
                continue
            relation_schema = _schema_for_op_field(create, relation)
            enum = relation_schema.get("enum", [])
            if not enum:
                continue
            kind = "related" if "related" in enum else enum[0]
            update = _select_update_operation(child)
            delete_other = next((p for p in delete.params if "other" in _norm_key(p)), None)
            delete_relation = next((p for p in delete.params if "relation" in _norm_key(p)), None)
            if update and delete_other and delete_relation:
                return (parent, child, create, delete, other, relation, kind, update,
                        delete_other, delete_relation)
    return None


def render_validated_relation_lifecycle(plan: Plan) -> str:
    selected = _select_relation_lifecycle(plan)
    if not selected:
        return "// validated-relation-lifecycle: no complete self-relation lifecycle was derived.\n"
    (parent, child, create_relation, delete_relation, other_field, relation_field,
     relation_kind, update_selection, delete_other_field, delete_relation_field) = selected
    _rank, _method_rank, update_js_field, update_raw_field, update_schema, update_op = update_selection
    parent_key, parent_id = _single_key_var(parent, "parent")
    child_key, task_a = _single_key_var(child, "taskA")
    task_b = "__taskBId"
    relation_js = _value_js(relation_kind)
    lines = ['bthread("validated-relation-lifecycle:contract-derived", function() {']

